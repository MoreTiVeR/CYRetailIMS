$("#btnSearch").on('click', function (event) {
    ShowLoading();
    event.preventDefault(); // Prevent the default form submission

    var val = $("#ddlBranch").val();
    var branchid = parseInt(val);
    var request = $.ajax({
        url: '/Report/SearchItemPriceTransactionReportByBranch',
        async: true,
        type: 'POST',
        dataType: 'JSON',
        data: { "branchid": branchid },
        success: function (response) {

            if (response.result) {
                ShowMessageSuccess(response.message);

                //Update the DataTable with the filtered data from the server
                console.log(response.data);
                //$("#tbItemTransactionLogReport").DataTable().clear().rows.add(response.data).draw();
            }
            else {
                AlertErrorNoTitle(response.message);
            }
            $("#tbItemTransactionLogReport").DataTable().clear().rows.add(response.data).draw();
            HideLoading();
        },
        failure: function (response) {
            AlertError(response.message);
        },
        error: function (response) {
            AlertError(response.message);
        }
    });
});